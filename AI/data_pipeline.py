# Download & Verarbeitung
# ---------------------------------------------------------------------------

def download_and_process(
    output_dir: str,
    tokenizer_dir: str,
    config: PipelineConfig,
    max_samples: int = None,
):
    """
    Hauptfunktion: Lädt Daten von HuggingFace, filtert und tokenisiert sie.
    """
    from datasets import load_dataset
    from tokenizer_train import CodeTokenizer
    import random

    rng = random.Random(42)
    tokenizer = CodeTokenizer(tokenizer_dir)
    quality_filter = QualityFilter(config)
    deduplicator = MinHashDeduplicator(
        num_perm=config.minhash_num_perm,
        threshold=config.jaccard_threshold,
    ) if config.dedup_enabled else None

    dataset_writer = TokenizedDataset(output_dir, split="train")

    total_processed = 0
    total_kept = 0
    filter_stats = {}

    for ds_config in config.datasets:
        print(f"\nLade Dataset: {ds_config['name']}")

        for lang in config.languages:
            print(f"  Sprache: {lang}")
            try:
                # Dataset laden (streaming für große Datensätze)
                ds = load_dataset(
                    ds_config["name"],
                    data_dir=f"data/{lang}",
                    split=ds_config["split"],
                    streaming=True,
                    trust_remote_code=True,
                )
            except Exception as e:
                print(f"    Fehler beim Laden: {e}")
                continue

            lang_count = 0
            max_per_lang = ds_config.get("max_samples_per_lang", 500_000)
            if max_samples:
                max_per_lang = min(max_per_lang, max_samples)

            for sample in ds:
                if lang_count >= max_per_lang:
                    break

                text = sample.get(ds_config["text_field"], "")
                if not text:
                    continue

                total_processed += 1

                # Qualitätsfilter
                ok, reason = quality_filter.is_valid(text, lang)
                if not ok:
                    filter_stats[reason] = filter_stats.get(reason, 0) + 1
                    continue

                # Deduplizierung
                if deduplicator and deduplicator.is_duplicate(text):
                    filter_stats["duplikat"] = filter_stats.get("duplikat", 0) + 1
                    continue

                # Tokenisieren
                filename = sample.get("max_stars_repo_path", f"file.{lang}")
                tokens = tokenizer.encode_file(text, filename=filename)

                # FIM Transformation (50% der Sequenzen)
                if rng.random() < config.fim_rate and len(tokens) > 20:
                    tokens = apply_fim(
                        tokens,
                        tokenizer.fim_pre,
                        tokenizer.fim_suf,
                        tokenizer.fim_mid,
                        tokenizer.eos_id,
                        rng=rng,
                    )

                # In Chunks aufteilen (max_seq_len)
                for i in range(0, len(tokens), config.max_seq_len):
                    chunk = tokens[i:i + config.max_seq_len]
                    if len(chunk) >= 64:  # Zu kurze Chunks überspringen
                        dataset_writer.add_tokens(chunk)

                total_kept += 1
                lang_count += 1

                if total_processed % 10_000 == 0:
                    ratio = total_kept / total_processed * 100
                    print(f"    Verarbeitet: {total_processed:,} | Behalten: {total_kept:,} ({ratio:.1f}%)")

    dataset_writer.finalize()

    print(f"\nFilter-Statistiken:")
    for reason, count in sorted(filter_stats.items(), key=lambda x: -x[1]):
        print(f"  {reason}: {count:,}")

    print(f"\nGesamt: {total_processed:,} verarbeitet, {total_kept:,} behalten ({total_kept/total_processed*100:.1f}%)")


# ---------------------------------------------------------------------------
# Statistiken
# ---------------------------------------------------------------------------

def print_stats(data_dir: str):
    """Gibt Statistiken über ein tokenisiertes Dataset aus."""
    data_path = Path(data_dir)

    for split in ["train", "val"]:
        meta_path = data_path / f"{split}_meta.json"
        if not meta_path.exists():
            continue

        with open(meta_path) as f:
            meta = json.load(f)

        tokens = meta["total_tokens"]
        docs = meta["total_docs"]
        shards = meta["num_shards"]
        size_gb = tokens * 2 / 1e9  # uint16 = 2 bytes

        print(f"\n{split.upper()} Split:")
        print(f"  Tokens:    {tokens:,} ({tokens/1e9:.2f}B)")
        print(f"  Dokumente: {docs:,}")
        print(f"  Shards:    {shards}")
        print(f"  Größe:     {size_gb:.2f} GB")
        print(f"  Avg Tokens/Doc: {tokens/docs:.0f}")

        # Trainingszeit schätzen (RTX 4070 Ti)
        # ~50K tokens/sec bei batch=4, seq=1024
        tokens_per_sec = 50_000
        hours = tokens / tokens_per_sec / 3600
        print(f"  Geschätzte Trainingszeit (4070 Ti): {hours:.0f}h ({hours/24:.1f} Tage)")


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(description="CodeLM Datenpipeline")
    subparsers = parser.add_subparsers(dest="command")

    # Download & Verarbeitung
    dl_parser = subparsers.add_parser("process", help="Daten laden, filtern und tokenisieren")
    dl_parser.add_argument("--output_dir", type=str, required=True)
    dl_parser.add_argument("--tokenizer_dir", type=str, required=True)
    dl_parser.add_argument("--languages", nargs="+", default=None)
    dl_parser.add_argument("--max_samples", type=int, default=None, help="Max Samples (für Tests)")
    dl_parser.add_argument("--no_dedup", action="store_true", help="Deduplizierung deaktivieren")
    dl_parser.add_argument("--fim_rate", type=float, default=0.5)

    # Statistiken
    stats_parser = subparsers.add_parser("stats", help="Dataset-Statistiken anzeigen")
    stats_parser.add_argument("--data_dir", type=str, required=True)

    args = parser.parse_args()

    if args.command == "process":
        config = PipelineConfig()
        if args.languages:
            config.languages = args.languages
        if args.no_dedup:
            config.dedup_enabled = False
        config.fim_rate = args.fim_rate

        download_and_process(
            output_dir=args.output_dir,
            tokenizer_dir=args.tokenizer_dir,
            config=config,
            max_samples=args.max_samples,
        )

    elif args.command == "stats":
        print_stats(args.data_dir)

    else:
        parser.print_help()


if __name__ == "__main__":
    main()
