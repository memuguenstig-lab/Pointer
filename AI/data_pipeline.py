"""
Datenpipeline für CodeLM Pre-Training
Lädt, filtert, dedupliziert und tokenisiert Code-Daten.

Schritte:
  1. Download von HuggingFace Datasets (The Stack v2, StarCoder Data)
  2. Qualitätsfilterung
  3. Deduplizierung (MinHash LSH)
  4. Tokenisierung + Speicherung als .bin Dateien (Memory-mapped)

Verwendung:
    # Schritt 1: Daten herunterladen und filtern
    python data_pipeline.py download --output_dir ./data/raw --languages python javascript typescript rust

    # Schritt 2: Tokenisieren
    python data_pipeline.py tokenize --raw_dir ./data/raw --output_dir ./data/tokenized --tokenizer_dir ./tokenizer

    # Schritt 3: Statistiken
    python data_pipeline.py stats --data_dir ./data/tokenized
"""

