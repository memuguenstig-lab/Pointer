# ---------------------------------------------------------------------------
# Konfiguration
# ---------------------------------------------------------------------------

@dataclass
class PipelineConfig:
    # Qualitätsfilter
    min_chars: int = 100
    max_chars: int = 500_000
    max_non_ascii_ratio: float = 0.3
    max_line_length: int = 1000       # Zeilen länger als das → wahrscheinlich minified
    min_lines: int = 3
    max_avg_line_length: float = 200  # Durchschnittliche Zeilenlänge

    # Deduplizierung
    dedup_enabled: bool = True
    minhash_num_perm: int = 128       # Mehr = genauer, aber langsamer
    jaccard_threshold: float = 0.8    # Ähnlichkeit ab der dedupliziert wird

    # Tokenisierung
    max_seq_len: int = 1024           # Tokens pro Sequenz (für Training)
    fim_rate: float = 0.5             # 50% der Sequenzen als FIM formatieren

    # Unterstützte Sprachen (Priorität)
    languages: list = field(default_factory=lambda: [
        "python", "javascript", "typescript", "rust",
        "go", "java", "cpp", "c", "csharp",
        "html", "css", "sql", "shell",
    ])

    # HuggingFace Datasets
    datasets: list = field(default_factory=lambda: [
        {
            "name": "bigcode/the-stack-v2-dedup",
            "split": "train",
            "text_field": "content",
            "lang_field": "lang",
            "max_samples_per_lang": 500_000,
        },
        {
            "name": "bigcode/starcoderdata",
            "split": "train",
            "text_field": "content",
            "lang_field": "lang",
            "max_samples_per_lang": 200_000,
        },
    ])


# ---------------------------------------------------------------------------
# Qualitätsfilter
# ---------------------------------------------------------------------------

class QualityFilter:
    def __init__(self, config: PipelineConfig):
        self.config = config

        # Regex für häufige Müll-Muster
        self._auto_generated = re.compile(
            r"(auto.?generated|do not edit|generated by|this file was generated)",
            re.IGNORECASE
        )
        self._minified = re.compile(r"^.{500,}$", re.MULTILINE)

    def is_valid(self, text: str, lang: str = None) -> tuple[bool, str]:
        """
        Prüft ob ein Code-Snippet qualitativ hochwertig ist.
        Returns: (is_valid, reason_if_invalid)
        """
        # Länge
        if len(text) < self.config.min_chars:
            return False, "zu_kurz"
        if len(text) > self.config.max_chars:
            return False, "zu_lang"

        # Zeilen
        lines = text.splitlines()
        if len(lines) < self.config.min_lines:
            return False, "zu_wenig_zeilen"

        # Durchschnittliche Zeilenlänge (Minified Code erkennen)
        avg_line_len = sum(len(l) for l in lines) / len(lines)
        if avg_line_len > self.config.max_avg_line_length:
            return False, "minified"

        # Sehr lange Einzelzeilen
        max_line = max(len(l) for l in lines)
        if max_line > self.config.max_line_length:
            return False, "zeile_zu_lang"

        # Non-ASCII Ratio
        non_ascii = sum(1 for c in text if ord(c) > 127)
        if non_ascii / len(text) > self.config.max_non_ascii_ratio:
            return False, "zu_viel_non_ascii"

        # Auto-generierter Code (oft wenig Lernwert)
        if self._auto_generated.search(text[:500]):
            return False, "auto_generiert"

        return True, ""

    def filter_batch(self, samples: list[dict]) -> list[dict]:
        """Filtert einen Batch von Samples."""
        valid = []
        stats = {}
        for sample in samples:
            text = sample.get("content", sample.get("text", ""))
            lang = sample.get("lang", "")
            ok, reason = self.is_valid(text, lang)
            if ok:
                valid.append(sample)
            else:
                stats[reason] = stats.get(reason, 0) + 1
        return valid, stats


# ---------------------------------------------------------------------------
# MinHash Deduplizierung
# ---------------------------------------------------------------------------

class MinHashDeduplicator:
    """
    Einfache MinHash-basierte Deduplizierung.
    Für große Datensätze: datasketch Library verwenden.
    """

    def __init__(self, num_perm: int = 128, threshold: float = 0.8):
        self.num_perm = num_perm
        self.threshold = threshold
        self.seen_hashes: set = set()

        # Zufällige Hash-Parameter (a, b für ax+b mod p)
        import random
        rng = random.Random(42)
        self._a = [rng.randint(1, (1 << 31) - 1) for _ in range(num_perm)]
        self._b = [rng.randint(0, (1 << 31) - 1) for _ in range(num_perm)]
        self._p = (1 << 31) - 1  # Mersenne Prime

    def _shingles(self, text: str, k: int = 5) -> set[int]:
        """Erstellt k-Gramm Shingles aus dem Text."""
        # Normalisierung: Whitespace kollabieren
        text = re.sub(r'\s+', ' ', text.lower())
        shingles = set()
        for i in range(len(text) - k + 1):
            shingle = text[i:i+k]
            shingles.add(hash(shingle) & 0xFFFFFFFF)
        return shingles

    def _minhash(self, shingles: set[int]) -> tuple[int, ...]:
        """Berechnet MinHash Signatur."""
        if not shingles:
            return tuple([0] * self.num_perm)
        sig = []
        for i in range(self.num_perm):
            min_val = min(
                (self._a[i] * s + self._b[i]) % self._p
                for s in shingles
            )
            sig.append(min_val)
        return tuple(sig)

    def _signature_hash(self, sig: tuple) -> str:
        """Kompakter Hash der Signatur für schnellen Lookup."""
        # Nur erste 32 Werte für Geschwindigkeit
        return hashlib.md5(str(sig[:32]).encode()).hexdigest()

    def is_duplicate(self, text: str) -> bool:
        """Prüft ob ein Text ein Duplikat ist."""
        shingles = self._shingles(text)
        sig = self._minhash(shingles)
        sig_hash = self._signature_hash(sig)

        if sig_hash in self.seen_hashes:
            return True

        self.seen_hashes.add(sig_hash)
        return False

    def deduplicate(self, texts: list[str]) -> list[bool]:
        """Gibt für jeden Text zurück ob er behalten werden soll."""
        return [not self.is_duplicate(t) for t in texts]


# ---------------------------------------------------------------------------
# FIM (Fill-in-the-Middle) Transformation
# ---------------------------------------------------------------------------

def apply_fim(tokens: list[int], fim_pre_id: int, fim_suf_id: int, fim_mid_id: int,
              eos_id: int, rng=None) -> list[int]:
    """
    Transformiert eine Token-Sequenz in FIM-Format.
    Wählt zufällig einen Split-Punkt und formatiert als:
    [fim_pre] prefix [fim_suf] suffix [fim_mid] middle [eos]
    """
    import random
    if rng is None:
        rng = random.Random()

    n = len(tokens)
    if n < 10:
        return tokens

    # Zufällige Split-Punkte
    split1 = rng.randint(1, n - 2)
    split2 = rng.randint(split1 + 1, n - 1)

    prefix = tokens[:split1]
    middle = tokens[split1:split2]
    suffix = tokens[split2:]

    # FIM Format: prefix → suffix → middle (PSM Format, wie in StarCoder)
    return [fim_pre_id] + prefix + [fim_suf_id] + suffix + [fim_mid_id] + middle + [eos_id]


