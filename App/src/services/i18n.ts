// ── Runtime state ──────────────────────────────────────────────────────────

let currentLanguage: Language = (localStorage.getItem('pointer-language') as Language) || 'en';
const listeners = new Set<() => void>();

export function setLanguage(lang: Language) {
  currentLanguage = lang;
  localStorage.setItem('pointer-language', lang);
  listeners.forEach(fn => fn());
}

export function getLanguage(): Language { return currentLanguage; }

export function getSupportedLanguages(): { code: Language; name: string }[] {
  return [
    { code: 'en', name: 'English' },
    { code: 'de', name: 'Deutsch' },
    { code: 'fr', name: 'Français' },
    { code: 'es', name: 'Español' },
    { code: 'zh', name: '中文' },
    { code: 'ja', name: '日本語' },
  ];
}

/** Translate a key, with optional variable interpolation: t('git.conflictsRemaining', { n: 3, s: 's' }) */
export function t(key: string, vars?: Record<string, string | number>): string {
  const table = translations[currentLanguage] ?? translations.en;
  let str = table[key] ?? translations.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

/** React hook — re-renders when language changes */
export function useTranslation() {
  const [, forceUpdate] = useState(0);
  useEffect(() => {
    const fn = () => forceUpdate(n => n + 1);
    listeners.add(fn);
    return () => { listeners.delete(fn); };
  }, []);
  return { t, language: currentLanguage, setLanguage };
}
